-- RECETARIO COLABORATIVO — ETAPA 2 del ABM: INGREDIENTES (LISTADO, ALTA Y EDICION)
-- Para ejecutar en Supabase > SQL Editor con el esquema del proyecto ya creado.
-- No altera tablas, no borra ingredientes y NO habilita la desactivacion.
-- Reejecutable: se recrean solo las dos politicas de escritura aqui definidas.

begin;

alter table public.ingredientes enable row level security;

-- El esquema inicial ya permite SELECT a visitantes y autenticados.
-- Mantener lectura de activos e inactivos: los ingredientes inactivos
-- deben continuar figurando en recetas existentes.
grant select on table public.ingredientes to anon, authenticated;

-- Restringir las operaciones REST: un usuario autenticado solo podra
-- enviar el campo nombre en INSERT y UPDATE; activo conserva su default true.
-- Sin DELETE ni escritura para visitantes.
revoke insert, update, delete on table public.ingredientes from anon, authenticated;
grant insert (nombre), update (nombre) on table public.ingredientes to authenticated;

-- La columna id es GENERATED BY DEFAULT AS IDENTITY.
grant usage, select on sequence public.ingredientes_id_seq to authenticated;

-- Alta exclusiva de administradores, identificados mediante auth.uid().
drop policy if exists "Admin crea ingredientes" on public.ingredientes;
create policy "Admin crea ingredientes"
on public.ingredientes
for insert
to authenticated
with check (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.rol = 'admin'
    )
    and activo = true
);

-- Cambio de nombre exclusivo de administradores.
-- El cambio se refleja en todas las recetas porque las tablas
-- receta_ingredientes apuntan al ID del catalogo central.
drop policy if exists "Admin renombra ingredientes" on public.ingredientes;
create policy "Admin renombra ingredientes"
on public.ingredientes
for update
to authenticated
using (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.rol = 'admin'
    )
)
with check (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.rol = 'admin'
    )
);

commit;

