-- RECETARIO COLABORATIVO - ESQUEMA INICIAL (v1)
-- Ejecutar en Supabase > SQL Editor > New query > Run.
-- Diseñado para un proyecto nuevo, sin tablas anteriores con estos nombres.
-- Incluye 9 tablas, relaciones, índices, perfil al registrarse y RLS inicial.
-- No incluye políticas de escritura ni funciones de aprobación: se agregan después.

begin;

-- 1. PERFIL DE USUARIO (complementa auth.users de Supabase)
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text,
    nombre text,
    rol text not null default 'usuario'
        check (rol in ('usuario', 'admin')),
    creado_en timestamptz not null default now()
);

-- 2. CATEGORIAS / ETIQUETAS
create table if not exists public.categorias (
    id bigint generated by default as identity primary key,
    nombre text not null check (length(btrim(nombre)) > 0),
    activa boolean not null default true,
    creada_en timestamptz not null default now()
);

-- No duplicar nombres ignorando mayúsculas y espacios laterales.
create unique index if not exists categorias_nombre_unico
    on public.categorias (lower(btrim(nombre)));

-- Categoria de respaldo. Se protege en la lógica administrativa posterior.
insert into public.categorias (nombre)
values ('General')
on conflict do nothing;

-- 3. INGREDIENTES: catalogo unico para todas las recetas
create table if not exists public.ingredientes (
    id bigint generated by default as identity primary key,
    nombre text not null check (length(btrim(nombre)) > 0),
    activo boolean not null default true,
    creado_en timestamptz not null default now()
);

create unique index if not exists ingredientes_nombre_unico
    on public.ingredientes (lower(btrim(nombre)));

-- 4. RECETAS: identidad, autor y baja logica
create table if not exists public.recetas (
    id bigint generated by default as identity primary key,
    autor_id uuid not null references public.profiles(id),
    creada_en timestamptz not null default now(),
    eliminada_en timestamptz
);

create index if not exists recetas_autor_idx
    on public.recetas (autor_id);

-- 5. VERSIONES: se publica una version y otra puede estar pendiente
create table if not exists public.receta_versiones (
    id bigint generated by default as identity primary key,
    receta_id bigint not null references public.recetas(id) on delete cascade,
    numero integer not null check (numero > 0),
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'rechazada', 'publicada', 'anterior', 'descartada')),
    titulo text not null check (length(btrim(titulo)) > 0),
    descripcion text,
    tiempo_minutos integer check (tiempo_minutos > 0),
    porciones integer not null check (porciones > 0),
    dificultad text check (dificultad in ('facil', 'media', 'dificil')),
    imagen_path text, -- ruta del objeto en Supabase Storage, puede ser NULL
    motivo_rechazo text,
    creada_en timestamptz not null default now(),
    actualizada_en timestamptz not null default now(),
    unique (receta_id, numero)
);

create index if not exists receta_versiones_receta_idx
    on public.receta_versiones (receta_id);

-- Nunca dos versiones publicadas ni dos pendientes para la misma receta.
create unique index if not exists receta_una_version_publicada
    on public.receta_versiones (receta_id)
    where estado = 'publicada';

create unique index if not exists receta_una_version_pendiente
    on public.receta_versiones (receta_id)
    where estado = 'pendiente';

-- 6. CATEGORIAS POR VERSION (una receta puede tener varias etiquetas)
create table if not exists public.version_categorias (
    version_id bigint not null references public.receta_versiones(id) on delete cascade,
    categoria_id bigint not null references public.categorias(id),
    primary key (version_id, categoria_id)
);

create index if not exists version_categorias_categoria_idx
    on public.version_categorias (categoria_id);

-- 7. INGREDIENTES POR VERSION (sin duplicados en una misma version)
create table if not exists public.version_ingredientes (
    version_id bigint not null references public.receta_versiones(id) on delete cascade,
    ingrediente_id bigint not null references public.ingredientes(id),
    cantidad numeric(12, 3) not null check (cantidad > 0),
    unidad text not null check (unidad in (
        'g', 'kg', 'ml', 'l', 'unidades',
        'cucharaditas', 'cucharadas', 'tazas', 'pizcas'
    )),
    primary key (version_id, ingrediente_id)
);

create index if not exists version_ingredientes_ingrediente_idx
    on public.version_ingredientes (ingrediente_id);

-- 8. PASOS DE PREPARACION, ORDENADOS EN CADA VERSION
create table if not exists public.version_pasos (
    version_id bigint not null references public.receta_versiones(id) on delete cascade,
    orden integer not null check (orden > 0),
    descripcion text not null check (length(btrim(descripcion)) > 0),
    primary key (version_id, orden)
);

-- 9. SOLICITUDES INDEPENDIENTES DE INGREDIENTES
create table if not exists public.solicitudes_ingredientes (
    id bigint generated by default as identity primary key,
    solicitante_id uuid not null references public.profiles(id),
    nombre_solicitado text not null check (length(btrim(nombre_solicitado)) > 0),
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'aprobada', 'rechazada', 'asociada')),
    ingrediente_id bigint references public.ingredientes(id),
    creada_en timestamptz not null default now(),
    resuelta_en timestamptz,
    check (estado not in ('aprobada', 'asociada') or ingrediente_id is not null)
);

create index if not exists solicitudes_ingredientes_solicitante_idx
    on public.solicitudes_ingredientes (solicitante_id);

create index if not exists solicitudes_ingredientes_estado_idx
    on public.solicitudes_ingredientes (estado);

-- ALTA AUTOMATICA DEL PERFIL DE CADA USUARIO NUEVO
-- El rol siempre parte de 'usuario': no se toma del formulario ni del metadata.
create or replace function public.crear_perfil_recetario()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
    insert into public.profiles (id, email, nombre)
    values (
        new.id,
        new.email,
        coalesce(new.raw_user_meta_data ->> 'nombre', split_part(new.email, '@', 1))
    );
    return new;
end;
$$;

-- No exponer innecesariamente esta función para llamadas directas de la API.
revoke all on function public.crear_perfil_recetario() from public, anon, authenticated;

drop trigger if exists recetario_usuario_nuevo on auth.users;
create trigger recetario_usuario_nuevo
    after insert on auth.users
    for each row execute function public.crear_perfil_recetario();

-- Compatibilidad con usuarios registrados antes de ejecutar este script.
insert into public.profiles (id, email, nombre)
select id, email,
       coalesce(raw_user_meta_data ->> 'nombre', split_part(email, '@', 1))
from auth.users
on conflict (id) do nothing;

-- SEGURIDAD BASE: RLS HABILITADO EN TODAS LAS TABLAS
alter table public.profiles enable row level security;
alter table public.categorias enable row level security;
alter table public.ingredientes enable row level security;
alter table public.recetas enable row level security;
alter table public.receta_versiones enable row level security;
alter table public.version_categorias enable row level security;
alter table public.version_ingredientes enable row level security;
alter table public.version_pasos enable row level security;
alter table public.solicitudes_ingredientes enable row level security;

-- Permisos SQL mínimos para lectura por Data API. RLS limita las filas.
grant usage on schema public to anon, authenticated;
grant select on public.profiles to authenticated;
grant select on public.categorias, public.ingredientes to anon, authenticated;

-- LECTURA INICIAL SEGURA: perfiles propios, etiquetas e ingredientes.
-- Las políticas de recetas, propuestas y escritura se agregan en el paso de RLS.
drop policy if exists "Leer mi perfil" on public.profiles;
create policy "Leer mi perfil" on public.profiles
    for select to authenticated
    using (id = (select auth.uid()));

drop policy if exists "Leer categorias activas" on public.categorias;
create policy "Leer categorias activas" on public.categorias
    for select to anon, authenticated
    using (activa = true);

-- Los inactivos siguen siendo legibles porque pueden figurar en recetas existentes.
drop policy if exists "Leer ingredientes" on public.ingredientes;
create policy "Leer ingredientes" on public.ingredientes
    for select to anon, authenticated
    using (true);

commit;
